// ── Whole-coin designer art ingest (v3, 2026-10-02) ─────────────────────────
// Designers may deliver the ENTIRE coin as an image (square, transparent
// background, the coin filling the canvas): docs/badge-art/coins/<id>.webp
// (or .png). This script copies them to public/badge-coins/ and generates
// src/badges/coinsArt.js. Badges with a coin image render it as the collected
// front face; everything else (outline state, engraved back, badges without
// coin art) keeps the programmatic medallion.  Run: node scripts/ingestCoins.mjs
import { readdirSync, copyFileSync, writeFileSync, mkdirSync } from 'node:fs'

const SRC = new URL('../docs/badge-art/coins/', import.meta.url).pathname
const PUB = new URL('../public/badge-coins/', import.meta.url).pathname
const OUT = new URL('../src/badges/coinsArt.js', import.meta.url).pathname

mkdirSync(PUB, { recursive: true })
let files = []
try { files = readdirSync(SRC).filter(f => /\.(webp|png)$/i.test(f)) } catch {}
const map = {}
for (const f of files) {
  const id = f.replace(/\.(webp|png)$/i, '')
  copyFileSync(SRC + f, PUB + f)
  map[id] = '/badge-coins/' + f
}
writeFileSync(OUT, '// AUTO-GENERATED by scripts/ingestCoins.mjs from docs/badge-art/coins/*\n' +
  '// Whole-coin designer images — collected front face. Do not edit.\n' +
  'export const COINS = ' + JSON.stringify(map, null, 2) + '\n')
console.log('ingested', files.length, 'coin image(s):', Object.keys(map).join(', ') || '(none)')
